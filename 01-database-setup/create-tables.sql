-- TABLE 1: DEPARTMENTS
CREATE TABLE departments (
    department_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_code VARCHAR(20) NOT NULL UNIQUE,
    department_name VARCHAR(100) NOT NULL,
    faculty_name VARCHAR(100) NOT NULL
);

-- TABLE 2: LECTURERS
CREATE TABLE lecturers (
    lecturer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_number VARCHAR(30) NOT NULL UNIQUE,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    email VARCHAR(100) UNIQUE,
    phone_number VARCHAR(20),
    department_id INTEGER NOT NULL,
    CONSTRAINT fk_lecturers_department
        FOREIGN KEY (department_id)
        REFERENCES departments(department_id)
);

-- TABLE 3: COURSES
CREATE TABLE courses (
    course_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code VARCHAR(20) NOT NULL UNIQUE,
    course_title VARCHAR(150) NOT NULL,
    credit_unit INTEGER NOT NULL CHECK (credit_unit > 0),
    department_id INTEGER NOT NULL,
    CONSTRAINT fk_courses_department
        FOREIGN KEY (department_id)
        REFERENCES departments(department_id)
);

-- TABLE 4: SEMESTERS
CREATE TABLE semesters (
    semester_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year VARCHAR(20) NOT NULL,
    semester_name VARCHAR(30) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    CONSTRAINT chk_semester_dates
        CHECK (end_date > start_date),
    CONSTRAINT uq_academic_year_semester
        UNIQUE (academic_year, semester_name)
);

-- TABLE 5: STUDENTS
CREATE TABLE students (
    student_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_number VARCHAR(30) NOT NULL UNIQUE,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    email VARCHAR(100) UNIQUE,
    phone_number VARCHAR(20),
    date_of_birth DATE,
    gender VARCHAR(20),
    admission_date DATE,
    department_id INTEGER NOT NULL,
    CONSTRAINT fk_students_department
        FOREIGN KEY (department_id)
        REFERENCES departments(department_id)
);

-- TABLE 6: COURSE OFFERINGS
CREATE TABLE course_offerings (
    offering_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id INTEGER NOT NULL,
    semester_id INTEGER NOT NULL,
    lecturer_id INTEGER NOT NULL,
    offering_code VARCHAR(30) NOT NULL UNIQUE,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    CONSTRAINT fk_offerings_course
        FOREIGN KEY (course_id)
        REFERENCES courses(course_id),
    CONSTRAINT fk_offerings_semester
        FOREIGN KEY (semester_id)
        REFERENCES semesters(semester_id),
    CONSTRAINT fk_offerings_lecturer
        FOREIGN KEY (lecturer_id)
        REFERENCES lecturers(lecturer_id)
);

-- TABLE 7: ENROLLMENTS
CREATE TABLE enrollments (
    enrollment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL,
    offering_id INTEGER NOT NULL,
    enrollment_date DATE NOT NULL,
    enrollment_status VARCHAR(30) DEFAULT 'Enrolled',
    CONSTRAINT fk_enrollments_student
        FOREIGN KEY (student_id)
        REFERENCES students(student_id),
    CONSTRAINT fk_enrollments_offering
        FOREIGN KEY (offering_id)
        REFERENCES course_offerings(offering_id),
    CONSTRAINT uq_student_offering
        UNIQUE (student_id, offering_id)
);

-- TABLE 8: RESULTS
CREATE TABLE results (
    result_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrollment_id INTEGER NOT NULL UNIQUE,
    ca_score NUMERIC(5,2) NOT NULL
        CHECK (ca_score BETWEEN 0 AND 40),
    examination_score NUMERIC(5,2) NOT NULL
        CHECK (examination_score BETWEEN 0 AND 60),
    total_score NUMERIC(5,2) NOT NULL
        CHECK (total_score BETWEEN 0 AND 100),
    grade VARCHAR(2) NOT NULL
        CHECK (grade IN ('A', 'B', 'C', 'D', 'F')),
    remarks VARCHAR(100),
    CONSTRAINT fk_results_enrollment
        FOREIGN KEY (enrollment_id)
        REFERENCES enrollments(enrollment_id)
);

